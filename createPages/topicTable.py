TOPIC_TABLE = {}
TOPIC_GROUP_OF = {} # topic title -> subject heading
for _group, _topics in TOPIC_GROUPS.items():
    assert isinstance( _group, str ) and _group and _topics, f"{_group=}"
    for _topic, _items in _topics.items():
        assert _topic not in TOPIC_TABLE, f"Topic {_topic!r} occurs in both {TOPIC_GROUP_OF[_topic]!r} and {_group!r}"
        TOPIC_TABLE[_topic] = _items
        TOPIC_GROUP_OF[_topic] = _group

for _topic, _items in TOPIC_TABLE.items():
    assert isinstance( _topic, str )
    assert isinstance( _items, list ) and _items, f"{_topic=}"
    for _item in _items:
        assert isinstance( _item, str ), f"{_topic=} {_item=}"
        if _item.startswith( 'H3 ' ): continue
        if '/' in _item: # assume it's a lemma page link
            assert _item.count( '/' ) == 1, f"{_topic=} {_item=}"
            _part1, _part2 = _item.split( '/' )
            assert _part1 in ('HebLem','GrkLem'), f"{_topic=} {_item=}"
        else: # assume it's a reference -- either a verse or a verse or chapter range
            assert ' ' not in _item, f"{_topic=} {_item=}"
            _BBB, _refRest = _item.split( '_' ) # This split will fail if it's not a valid scripture reference
            try:
                _C, _Vs = _refRest.split( ':' )
                assert _C.isdigit(), f"{_topic=} {_item=}"
            except ValueError:
                assert _refRest.isdigit(), f"{_topic=} {_item=}"
